import { randomUUID } from 'node:crypto';
import { PrismaClient } from '@prisma/client';
import { ensureVillaInventory } from './villa-inventory';
import { InventoryService } from '../inventory/inventory.service';
import { RoomOutOfServiceCalendarService } from '../room-out-of-service/room-out-of-service-calendar.service';
import { PricingService } from '../pricing/pricing.service';
import { BookingService } from '../booking/booking.service';
import { PropertyService } from './property.service';
import { RoomService } from '../room/room.service';
import { ICalCalendarService } from '../ical-calendar/ical-calendar.service';

const integration = process.env.RUN_VILLA_INTEGRATION === 'true' ? describe : describe.skip;

integration('Whole-villa inventory integration (rolled back)', () => {
  const prisma = new PrismaClient();
  afterAll(() => prisma.$disconnect());

  it('supports local rates, booking, edits, legacy occupancy, blocking and hotel inventory', async () => {
    const rollback = new Error('rollback test data');
    await expect(prisma.$transaction(async tx => {
      const db = new Proxy(tx, { get: (target, key) => key === '$transaction' ? async (callback: (client: typeof tx) => unknown) => callback(tx) : Reflect.get(target, key) });
      const audit = { record: jest.fn() };
      const background = { enqueue: jest.fn(), queueInventorySyncsForProperty: jest.fn() };
      const roomCalendar = new RoomOutOfServiceCalendarService(db as never);
      const inventory = new InventoryService(db as never, audit as never, {} as never, roomCalendar);
      const pricing = new PricingService(db as never, roomCalendar);
      const booking = new BookingService(db as never, background as never, audit as never, inventory, {} as never, pricing);
      const properties = new PropertyService(db as never);
      const villa = await properties.createProperty({ name: 'Villa integration test', code: randomUUID(), address: 'Test', property_type: 'RENTAL_VILLAS' });
      const unit = await ensureVillaInventory(tx, villa.id);
      const again = await ensureVillaInventory(tx, villa.id);
      expect(again.category.id).toBe(unit.category.id);
      expect(await tx.room.count({ where: { propertyId: villa.id } })).toBe(1);
      expect(unit.ratePlan.isActive).toBe(false);
      const guest = await tx.guest.create({ data: { propertyId: villa.id, name: 'Test guest', phone: '1234567890', idProof: 'Passport: TEST123', address: 'Test' } });
      const request = { property_id: villa.id, guest_id: guest.id, check_in_date: '2030-01-10', check_out_date: '2030-01-12' };
      await expect(booking.createDirectReservation(request)).rejects.toThrow('Set the nightly villa rate');
      await properties.updateVillaRate(villa.id, { nightly_rate: 7500 });
      const created = await booking.createDirectReservation(request);
      expect(created.total_amount).toBe(15000);
      expect(background.queueInventorySyncsForProperty).not.toHaveBeenCalled();
      expect(created.rooms).toHaveLength(1);
      await expect(booking.createDirectReservation(request)).rejects.toThrow('Insufficient inventory');
      await expect(booking.createDirectReservation({ ...request, room_count: 2 })).rejects.toThrow('one entire property');
      await booking.updateDirectReservation(created.id, { ...request, check_out_date: '2030-01-13' });
      await booking.checkInReservationRoom(created.rooms[0].id, {});
      const checkedIn = await tx.reservationRoom.findUniqueOrThrow({ where: { id: created.rooms[0].id } });
      expect(checkedIn.status).toBe('CHECKED_IN');
      expect(checkedIn.roomId).toBe(unit.room.id);
      await expect(inventory.createInventoryBlock({ property_id: villa.id, from_date: '2030-01-11', to_date: '2030-01-11', blocked_rooms: 1, reason: 'Test' })).rejects.toThrow('Cannot block');
      const block = await inventory.createInventoryBlock({ property_id: villa.id, from_date: '2030-01-15', to_date: '2030-01-16', blocked_rooms: 1, reason: 'Test' });
      const getRows = () => inventory.rebuildCalendarRange({ propertyId: villa.id, from: new Date('2030-01-10'), to: new Date('2030-01-20') }, tx);
      let rows = await getRows();
      expect(rows.every(row => row.totalRooms === 1)).toBe(true);
      expect(rows.find(row => row.stayDate.toISOString().startsWith('2030-01-15'))?.availableRooms).toBe(0);
      await inventory.removeInventoryBlock(block.id, false);
      rows = await getRows();
      expect(rows.find(row => row.stayDate.toISOString().startsWith('2030-01-15'))?.availableRooms).toBe(1);
      const legacyCategory = await tx.roomCategory.create({ data: { propertyId: villa.id, code: 'LEGACY', name: 'Old room type' } });
      const legacyRoom = await tx.room.create({ data: { propertyId: villa.id, roomCategoryId: legacyCategory.id, roomNumber: '101' } });
      await tx.reservationRoom.update({ where: { id: created.rooms[0].id }, data: { roomCategoryId: legacyCategory.id, roomId: legacyRoom.id } });
      rows = await getRows();
      expect(rows.find(row => row.stayDate.toISOString().startsWith('2030-01-11'))?.availableRooms).toBe(0);
      expect(rows.every(row => row.totalRooms === 1)).toBe(true);
      await tx.reservationRoom.update({ where: { id: created.rooms[0].id }, data: { status: 'CANCELLED' } });
      rows = await getRows();
      expect(rows.find(row => row.stayDate.toISOString().startsWith('2030-01-11'))?.availableRooms).toBe(1);
      const task = await tx.housekeepingTask.create({ data: { propertyId: villa.id, roomId: legacyRoom.id } });
      const period = await tx.roomOutOfServicePeriod.create({ data: { propertyId: villa.id, roomId: legacyRoom.id, fromDate: new Date('2030-01-18'), toDate: new Date('2030-01-19'), reason: 'Repairs' } });
      const rooms = new RoomService(db as never, audit as never, background as never, inventory);
      await rooms.remove(legacyRoom.id);
      expect(await tx.room.findUnique({ where: { id: legacyRoom.id } })).toBeNull();
      expect((await tx.reservationRoom.findUniqueOrThrow({ where: { id: created.rooms[0].id } })).roomId).toBe(unit.room.id);
      expect((await tx.housekeepingTask.findUniqueOrThrow({ where: { id: task.id } })).roomId).toBe(unit.room.id);
      expect((await tx.roomOutOfServicePeriod.findUniqueOrThrow({ where: { id: period.id } })).roomId).toBe(unit.room.id);
      const ical = new ICalCalendarService(db as never, inventory);
      const content = 'BEGIN:VCALENDAR\r\nVERSION:2.0\r\nBEGIN:VEVENT\r\nUID:external-stay\r\nDTSTART;VALUE=DATE:20300201\r\nDTEND;VALUE=DATE:20300203\r\nSUMMARY:External stay\r\nEND:VEVENT\r\nEND:VCALENDAR';
      const feed = { property_id: villa.id, feed_key: 'test-feed', name: 'Test calendar', content };
      await expect(ical.syncInventory(feed, { sub: randomUUID(), email: 'test@example.com', role: 'ADMIN', organization_id: null, property_id: randomUUID() })).rejects.toThrow();
      const manual = await inventory.createInventoryBlock({ property_id: villa.id, from_date: '2030-02-10', to_date: '2030-02-10', blocked_rooms: 1, reason: 'Owner stay' });
      await ical.syncInventory(feed);
      await ical.syncInventory(feed);
      const importedBlock = (await inventory.listInventoryBlocks(villa.id)).find(block => block.source.startsWith('ICAL_IMPORT:'));
      expect(importedBlock?.source_name).toBe('Test calendar');
      await expect(inventory.removeInventoryBlock(importedBlock!.id, false)).rejects.toThrow('Imported dates are managed by their source calendar');
      expect(await tx.inventoryBlock.count({ where: { propertyId: villa.id, source: { startsWith: 'ICAL_IMPORT:' } } })).toBe(1);
      const importedRows = await inventory.rebuildCalendarRange({ propertyId: villa.id, from: new Date('2030-02-01'), to: new Date('2030-02-03') }, tx);
      expect(importedRows.find(row => row.stayDate.toISOString().startsWith('2030-02-01'))?.availableRooms).toBe(0);
      expect(importedRows.find(row => row.stayDate.toISOString().startsWith('2030-02-03'))?.availableRooms).toBe(1);
      await expect(booking.createDirectReservation({ ...request, check_in_date: '2030-02-01', check_out_date: '2030-02-03' })).rejects.toThrow('Insufficient inventory');
      await expect(ical.syncInventory({ ...feed, content: 'broken' })).rejects.toThrow('Invalid iCal');
      expect(await tx.inventoryBlock.count({ where: { propertyId: villa.id, source: { startsWith: 'ICAL_IMPORT:' } } })).toBe(1);
      await ical.syncInventory({ ...feed, feed_key: 'second-feed' });
      await ical.syncInventory({ ...feed, content: 'BEGIN:VCALENDAR\r\nVERSION:2.0\r\nEND:VCALENDAR' });
      expect(await tx.inventoryBlock.count({ where: { propertyId: villa.id, source: { startsWith: 'ICAL_IMPORT:' } } })).toBe(1);
      expect(await tx.inventoryBlock.findUnique({ where: { id: manual.id } })).not.toBeNull();
      await ical.syncInventory({ ...feed, feed_key: 'second-feed', content: content.replace('SUMMARY:External stay', 'STATUS:CANCELLED\r\nSUMMARY:External stay') });
      const releasedRows = await inventory.rebuildCalendarRange({ propertyId: villa.id, from: new Date('2030-02-01'), to: new Date('2030-02-02') }, tx);
      expect(releasedRows.every(row => row.availableRooms === 1)).toBe(true);
      const hotel = await tx.property.create({ data: { name: 'Hotel integration test', code: randomUUID(), address: 'Test' } });
      await expect(ical.syncInventory({ ...feed, property_id: hotel.id })).rejects.toThrow();
      const hotelCategory = await tx.roomCategory.create({ data: { propertyId: hotel.id, code: 'DELUXE', name: 'Deluxe' } });
      await tx.room.createMany({ data: ['1', '2'].map(roomNumber => ({ propertyId: hotel.id, roomCategoryId: hotelCategory.id, roomNumber })) });
      const hotelRows = await inventory.rebuildCalendarRange({ propertyId: hotel.id, from: new Date('2030-01-10'), to: new Date('2030-01-11') }, tx);
      expect(hotelRows.every(row => row.totalRooms === 2 && row.availableRooms === 2)).toBe(true);
      await expect(booking.createDirectReservation({ ...request, property_id: hotel.id })).rejects.toThrow('required for hotels');
      throw rollback;
    }, { timeout: 60000 })).rejects.toBe(rollback);
  }, 70000);
});
